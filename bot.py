def جلب_شموع_السعر(الزوج, الإطار="5د", الحد=100, شموع_مغلقة_فقط=True):
    رمز = رموز_Binance.get(الزوج.upper().strip())
    if not رمز:
        raise Exception(f"الزوج {الزوج} غير مدعوم. الأزواج المدعومة: {', '.join(رموز_Binance.keys())}")
    
    الفترة = الأطر_الزمنية.get(الإطار, {}).get("interval", "5m")
    
    try:
        res = requests.get(
            "https://api.binance.com/api/v3/klines",
            params={"symbol": رمز, "interval": الفترة, "limit": الحد},
            timeout=10
        )
        res.raise_for_status()
        بيانات = res.json()
        if not isinstance(بيانات, list) or len(بيانات) < 50:
            raise Exception("بيانات غير كافية من Binance")
        
        if شموع_مغلقة_فقط:
            بيانات = بيانات[:-1]
        
        if len(بيانات) < 40:
            raise Exception("بيانات غير كافية بعد حذف الشمعة غير المغلقة")
        
        الإغلاقات = [float(ش[4]) for ش in بيانات]
        الأسعار_الأعلى = [float(ش[2]) for ش in بيانات]
        الأسعار_الأدنى = [float(ش[3]) for ش in بيانات]
        الأحجام = [float(ش[5]) for ش in بيانات]
        return الإغلاقات, الأسعار_الأعلى, الأسعار_الأدنى, الأحجام

    except Exception as e:
        raise Exception(f"فشل جلب البيانات من Binance: {str(e)}. لا توجد بيانات احتياطية لضمان الشفافية.")

